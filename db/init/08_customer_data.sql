-- Customers, payment methods and addresses: the connections a graph is good at following (graph/sync.py).
--
-- Same tenant pattern as orders: every primary key includes merchant_id, and every foreign key carries merchant_id
-- too, so a row can never point at another merchant's row. All in one transaction: either every change applies, or none.
BEGIN;

CREATE TABLE customers (
    merchant_id TEXT NOT NULL REFERENCES merchants (id),
    id          TEXT NOT NULL,
    name        TEXT NOT NULL,
    PRIMARY KEY (merchant_id, id)
);

-- A card is identified by a fingerprint (a stable hash of the card number): the number itself is never stored.
-- UNIQUE (merchant_id, fingerprint) means one card is ONE row, however many customers pay with it. That is what makes
-- "two accounts share a card" visible: both customers' orders point at the same row.
CREATE TABLE payment_methods (
    merchant_id TEXT NOT NULL REFERENCES merchants (id),
    id          TEXT NOT NULL,
    fingerprint TEXT NOT NULL,
    last4       TEXT NOT NULL CHECK (last4 ~ '^[0-9]{4}$'),   -- what a person sees on a receipt; not sensitive
    PRIMARY KEY (merchant_id, id),
    UNIQUE (merchant_id, fingerprint)
);

-- An address is also one shared row. `normalized` is the lower-cased, punctuation-free form, so "12 Elm St." and
-- "12 elm st" are the same address (UNIQUE enforces that); `display` is how a person wrote it.
-- The id is generated by the database: nobody names an address. The natural key is `normalized`, and the way to
-- find-or-create one is  INSERT ... ON CONFLICT (merchant_id, normalized) DO UPDATE ... RETURNING id.
CREATE TABLE addresses (
    merchant_id TEXT   NOT NULL REFERENCES merchants (id),
    id          BIGINT GENERATED ALWAYS AS IDENTITY,
    normalized  TEXT   NOT NULL,
    display     TEXT NOT NULL,
    PRIMARY KEY (merchant_id, id),
    UNIQUE (merchant_id, normalized)
);

-- An order says who placed it, what paid for it and where it ships. The columns are NULLable so orders that predate
-- this change are still valid. (A composite foreign key with a NULL column is not checked: Postgres's default
-- MATCH SIMPLE. merchant_id is NOT NULL, so a NULL customer_id simply means "no customer recorded".)
ALTER TABLE orders
    ADD COLUMN customer_id         TEXT,
    ADD COLUMN payment_method_id   TEXT,
    ADD COLUMN shipping_address_id BIGINT,   -- addresses.id is a generated number, so this matches its type
    ADD FOREIGN KEY (merchant_id, customer_id)         REFERENCES customers (merchant_id, id),
    ADD FOREIGN KEY (merchant_id, payment_method_id)   REFERENCES payment_methods (merchant_id, id),
    ADD FOREIGN KEY (merchant_id, shipping_address_id) REFERENCES addresses (merchant_id, id);

-- Postgres does not index foreign-key columns by itself. The graph sync scans orders, and graph/bench.py's SQL
-- engines need these for a fair comparison with the graph.
CREATE INDEX orders_customer_idx       ON orders (merchant_id, customer_id);
CREATE INDEX orders_payment_method_idx ON orders (merchant_id, payment_method_id);
CREATE INDEX orders_address_idx        ON orders (merchant_id, shipping_address_id);

-- ---------------------------------------------------------------------------------------------------------------
-- Seed data, designed so the graph has something to find (acme):
--
--   ana --card 1111-- ben --address elm-- eve --card 3333-- fay        cy also uses card 1111
--   dee: no links at all (the control)
--
-- globex has a customer who uses a card with the SAME fingerprint as acme's card 1111, and ships to the SAME
-- normalized address as acme's elm: they are different merchants, so they must NOT link to the acme ring.
-- ---------------------------------------------------------------------------------------------------------------
INSERT INTO customers (merchant_id, id, name) VALUES
    ('acme',   'ana', 'Ana Alvarez'),
    ('acme',   'ben', 'Ben Brooks'),
    ('acme',   'cy',  'Cy Chen'),
    ('acme',   'dee', 'Dee Dixon'),
    ('acme',   'eve', 'Eve Evans'),
    ('acme',   'fay', 'Fay Foster'),
    ('globex', 'gus', 'Gus Grant');

INSERT INTO payment_methods (merchant_id, id, fingerprint, last4) VALUES
    ('acme',   'pm-1111', 'fp-1111', '1111'),
    ('acme',   'pm-2222', 'fp-2222', '2222'),
    ('acme',   'pm-3333', 'fp-3333', '3333'),
    ('globex', 'pm-1111', 'fp-1111', '1111');   -- same fingerprint as acme's, a different merchant: must not link

INSERT INTO addresses (merchant_id, normalized, display) VALUES
    ('acme',   '9 pine ave 94110',   '9 Pine Ave, 94110'),
    ('acme',   '12 elm st 94110',    '12 Elm St, 94110'),
    ('acme',   '4 maple rd 94110',   '4 Maple Rd, 94110'),
    ('acme',   '77 oak ln 94110',    '77 Oak Ln, 94110'),
    ('acme',   '31 birch ct 94110',  '31 Birch Ct, 94110'),
    ('globex', '12 elm st 94110',    '12 Elm St, 94110');   -- same normalized address as acme's: a different merchant, so a different row

-- The existing orders get a customer, a card and an address. The address is looked up by its text (the ids are generated).
UPDATE orders SET customer_id = 'ana', payment_method_id = 'pm-1111',
    shipping_address_id = (SELECT id FROM addresses WHERE merchant_id = 'acme' AND normalized = '9 pine ave 94110')
    WHERE merchant_id = 'acme' AND id = 'A100';
UPDATE orders SET customer_id = 'ben', payment_method_id = 'pm-1111',
    shipping_address_id = (SELECT id FROM addresses WHERE merchant_id = 'acme' AND normalized = '12 elm st 94110')
    WHERE merchant_id = 'acme' AND id = 'A200';
UPDATE orders SET customer_id = 'cy', payment_method_id = 'pm-1111',
    shipping_address_id = (SELECT id FROM addresses WHERE merchant_id = 'acme' AND normalized = '4 maple rd 94110')
    WHERE merchant_id = 'acme' AND id = 'A300';
UPDATE orders SET customer_id = 'gus', payment_method_id = 'pm-1111',
    shipping_address_id = (SELECT id FROM addresses WHERE merchant_id = 'globex' AND normalized = '12 elm st 94110')
    WHERE merchant_id = 'globex' AND id = 'A100';

-- ...and three new acme orders complete the picture.
INSERT INTO orders (merchant_id, id, item, total_cents, status, delivered_at, customer_id, payment_method_id, shipping_address_id)
SELECT 'acme', o.id, o.item, o.total_cents, 'delivered', now() - o.age, o.customer_id, o.payment_method_id, a.id
FROM (VALUES
    ('B100', 'speaker stand', 4500, interval '10 days', 'dee', 'pm-2222', '77 oak ln 94110'),
    ('B200', 'microphone',    7200, interval '8 days',  'eve', 'pm-3333', '12 elm st 94110'),
    ('B300', 'cable kit',     2100, interval '6 days',  'fay', 'pm-3333', '31 birch ct 94110')
) AS o (id, item, total_cents, age, customer_id, payment_method_id, address_text)
JOIN addresses a ON a.merchant_id = 'acme' AND a.normalized = o.address_text;

COMMIT;
